# Writes src/types/database.ts from a saved Supabase MCP generate_typescript_types result.
# usage: python3 scripts/write-types.py <tool-result.json>
import json, sys
raw = json.load(open(sys.argv[1]))
types = json.loads(raw[0]['text'])['types']
open('src/types/database.ts', 'w').write('// Generated by Supabase (generate_typescript_types). Do not edit by hand.\n' + types)
print(len(types.splitlines()), 'lines')
